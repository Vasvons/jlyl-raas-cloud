/**
 * 种子导入：医美行业合规规则（幂等）
 * 仅当某平台尚不存在 industry='medical_beauty' 的 manual 规则时才插入，
 * 已存在的规则不会被覆盖（用户手动编辑过的内容受保护）。
 */
export async function seedMedicalBeautyRules(): Promise<{ imported: number; skipped: number }> {
  let imported = 0;
  let skipped = 0;

  for (const rule of MEDICAL_BEAUTY_RULES) {
    try {
      // 检查该平台是否已存在医美行业的 manual 规则
      const existing = await query(
        `SELECT id FROM platform_compliance_rule
         WHERE platform = $1 AND source = 'manual' AND industry = 'medical_beauty'
         LIMIT 1`,
        [rule.platform],
      );
      if (existing.rows.length > 0) {
        skipped++;
        continue;
      }
      await createManualRule({
        platform: rule.platform,
        rule_title: rule.rule_title,
        rule_content: rule.rule_content,
        industry: 'medical_beauty',
      });
      imported++;
    } catch (e: any) {
      console.error(`[seedMedicalBeautyRules] 平台 ${rule.platform} 导入失败:`, e.message);
      skipped++;
    }
  }

  console.log(`[seedMedicalBeautyRules] 医美规则种子导入完成: 新增 ${imported} 条, 跳过 ${skipped} 条`);
  return { imported, skipped };
}
