// 手动添加关键词
router.post('/zlgjc/add', authMiddleware, async (req, res) => {
  try {
    // v2.5.36：代理强制用自己 userId
    const userId = isAgent(req) ? String(getUserId(req)) : req.body.userId;
    const { value, hxgjc, lxfs, keywordType, brandId } = req.body;
    if (!userId || !value) return res.json({ code: 400, message: '缺少参数' });
    // ON CONFLICT 去重：如果 (userid, value, keyword_type) 已存在则不插入
    await query(
      brandId
        ? `INSERT INTO zlgjc (value, hxgjc, userid, lxfs, keyword_type, brand_id)
           VALUES ($1, $2, $3, $4, $5, $6)
           ON CONFLICT (userid, value, keyword_type) DO NOTHING`
        : `INSERT INTO zlgjc (value, hxgjc, userid, lxfs, keyword_type)
           VALUES ($1, $2, $3, $4, $5)
           ON CONFLICT (userid, value, keyword_type) DO NOTHING`,
      brandId
        ? [value, hxgjc || value, userId, lxfs || '', keywordType || 0, parseInt(brandId)]
        : [value, hxgjc || value, userId, lxfs || '', keywordType || 0]
    );
    res.json({ code: 200, message: '添加成功' });
  } catch (e) {
    res.json({ code: 500, message: '服务器错误' });
  }
});

